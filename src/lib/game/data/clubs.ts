function montar(t: Tupla, modalidade: Modalidade): ClubSeed {
  return {
    nome: t[0], abrev: t[1], pais: t[2], estado: t[3], cidade: t[4],
    categoria: t[5], personalidade: t[6], orcamentoK: t[7], cores: [t[8], t[9]],
    modalidade,
  };
}

